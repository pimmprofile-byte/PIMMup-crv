# 12세(초6) 인지 프로파일 기반 스텝별 플레이타임 모델
# fixed = 영상·음성·연출 재생 등 압축 불가 고정시간(초)
# var   = 탐색·이해·연산·조작 등 인지/행동 가변시간(초, 기대값)
# err   = 시행착오 기대 손실 = P(실패) × 재시도 비용(초)
STEPS = [
 # no, 제목, 과제유형, fixed, var, err, 비고
 ("01","입장 토큰 · 도어락","매칭+입력",       0,  47,  8),
 ("02","토글 스위치 6채널","규칙적용+작업기억",0, 105, 30),
 ("03","등록 설문","입력+선택",               12,  68,  5),
 ("04","열매 다이얼 3개","시각부호화(각도)",  50,  90, 45),
 ("05","나뭇잎 퍼즐 8종 (①안)","형태매칭",     0,  88,  7),
 ("06","씨앗 심기","단순조작",                30,  28,  2),
 ("07","통나무 낚시","정밀조작",               8,  55, 17),
 ("08","배터리 · UV · 숲달력 7215","다단추론", 18, 205, 87),
 ("09","관찰일지 읽기","읽기+이해",            0, 140,  0),
 ("10","색깔 나뭇가지 동시당김","탐색+협응",  25, 100, 25),
 ("11","숨은 솔이 찾기","시각탐색",           15,  85, 10),
 ("12","정령 언어 번역기","탐색+조작",        40,  60,  5),
 ("13","자석 막대 · 쇠솔방울","전이조작",      0,  65,  7),
 ("14","솔이와의 대화(선택지)","읽기+선택",   85,  60,  0),
 ("15","창문 개방 · 토큰 태그","반응+탐색",   35,  50, 10),
 ("16","소화기 들기","지시수행",              18,  22,  0),
 ("17","빛의 제어반 결선","조합매칭",         32,  90, 18),
 ("18","솔이의 편지","관람+조작",             50,  70,  0),
 ("19","야외 씨앗 심기 · 맵핑","이동+관람",   75,  95,  0),
]
TRANS = 6 * (len(STEPS)-1)   # 스텝 간 전환 오버헤드

F = sum(s[3] for s in STEPS)
V = sum(s[4] for s in STEPS)
E = sum(s[5] for s in STEPS)
P50 = F + V + E + TRANS

def fmt(sec): return "%d:%02d" % (sec//60, sec%60)
print("="*78)
print("%-4s %-26s %-14s %6s %6s %6s %8s"%("SEQ","스텝","과제유형","고정","가변","시행착오","합계"))
print("-"*78)
for no,t,k,f,v,e in STEPS:
    print("%-4s %-26s %-14s %6d %6d %6d %8s"%(no,t[:26],k,f,v,e,fmt(f+v+e)))
print("-"*78)
print("%-46s %6d %6d %6d %8s"%("소계",F,V,E,fmt(F+V+E)))
print("%-46s %6s %6s %6s %8s"%("스텝 전환 오버헤드 (6초 × 18)","","","",fmt(TRANS)))
print("%-46s %6s %6s %6s %8s"%("P50 기대 플레이타임","","","",fmt(P50)))
print("="*78)
# 분포 — 가변+시행착오에만 배수 적용(고정시간은 불변)
for lab,m in [("P10 (빠른 팀)",0.66),("P25",0.82),("P50 (기대)",1.00),("P75",1.24),("P90 (막히는 팀)",1.52)]:
    t = F + (V+E+TRANS)*m
    print("%-18s %8s   목표 40분 대비 %+.0f분"%(lab,fmt(int(t)),(t-2400)/60))
print("="*78)
print("고정(연출·음성) %s / 가변(사고·조작) %s / 시행착오 %s"%(fmt(F),fmt(V+TRANS),fmt(E)))
print("가변+시행착오 비중: %.0f%%  ← 튜닝으로 줄일 수 있는 유일한 영역"%((V+E+TRANS)/P50*100))

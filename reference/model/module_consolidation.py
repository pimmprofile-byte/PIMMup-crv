# 캐리어 통합 산출 — 시퀀스 → 물리 유닛 매핑
NAIVE = [  # 통합 없이 위치별로 나눌 경우의 물리 유닛
 "엔트리액자","메인콘솔","다이얼하부장","퍼즐함","화분","통나무","배터리제어함",
 "자물쇠서랍함","레버+히든서랍","매립모니터+함","번역기거치","선택지버튼",
 "창문센서+실린더","소화기거치","빛의제어반","펜플로터","야외텐트",
]
UNITS = {
 "K1":("메인 콘솔 A","표준캐리어",["02","03","14"],
       ["메인 모니터","토글 6채널 보드","선택지 물리버튼"]),
 "K2":("메인 콘솔 B","표준캐리어",["03","04","05"],
       ["미니 모니터·입력부","열매 다이얼 3","하부장 EM 잠금"]),
 "K3":("메인 콘솔 C","표준캐리어",["11","12","13"],
       ["모노레버","솔방울 함·경사로","번역기 프레임 거치"]),
 "K4":("수납 벽면 A","표준캐리어",["07","08","09"],
       ["통나무 탑카트리지","배터리 제어함","숫자자물쇠 서랍"]),
 "K5":("수납 벽면 B","표준캐리어",["10","13","16","17"],
       ["색나뭇가지 레버뱅크","히든서랍 컬렉션","하강커버","빛의 제어반","소화기 거치"]),
 "U1":("엔트리 유닛","특수·옥외",["01"],["토큰 리더 액자","도어락"]),
 "U2":("창가 선반 유닛","특수",["06","15"],
       ["화분 감지","솔이 실린더","창문 리드스위치·토큰센서","연기 노즐"]),
 "U3":("상부 행잉 유닛","특수",["18"],["펜 플로터","예비기 슬롯"]),
 "X1":("야외 텐트 유닛","외부",["19"],["프로젝터","씨앗 감지"]),
}
seqs=set()
for k,(n,t,s,c) in UNITS.items(): seqs|=set(s)
print("커버 시퀀스: %d개  %s"%(len(seqs),"OK" if len(seqs)==19 else "누락!"))
missing={"%02d"%i for i in range(1,20)}-seqs
print("누락:",sorted(missing) if missing else "없음")
std=sum(1 for k,v in UNITS.items() if v[1]=="표준캐리어")
spc=sum(1 for k,v in UNITS.items() if v[1].startswith("특수"))
ext=sum(1 for k,v in UNITS.items() if v[1]=="외부")
tot=len(UNITS); cart=sum(len(v[3]) for v in UNITS.values())
print("\n표준캐리어 %d · 특수유닛 %d · 외부 %d  =  총 %d 유닛"%(std,spc,ext,tot))
print("카트리지 총 %d종"%cart)
print("통합 전 물리유닛 %d → 후 %d  (%.0f%% 감소)"%(len(NAIVE),tot,(1-tot/len(NAIVE))*100))
print("\n유닛당 평균 시퀀스: %.1f"%(sum(len(v[2]) for v in UNITS.values())/tot))
print("\n%-4s %-16s %-10s %-18s %s"%("ID","유닛","구분","시퀀스","카트리지"))
print("-"*96)
for k,(n,t,s,c) in UNITS.items():
    print("%-4s %-16s %-10s %-18s %s"%(k,n,t,"·".join("SEQ."+x for x in s),", ".join(c)))

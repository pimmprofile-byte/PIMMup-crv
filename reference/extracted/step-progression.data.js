function ul(arr){return "<ul>"+arr.map(x=>"<li>"+x+"</li>").join("")+"</ul>";}
function ulTech(arr){
  if(!arr||!arr.length) return "";
  return "<ul>"+arr.map(x=>{
    if(typeof x==="string" && x.startsWith("tbd:")) return '<li class="tbd">'+x.slice(4)+"</li>";
    return "<li>"+x+"</li>";
  }).join("")+"</ul>";
}
function techGrp(cls,icon,label,arr){
  if(!arr||!arr.length) return "";
  return `<div class="tech-grp ${cls}"><div class="tech-t">${icon} ${label}</div>${ulTech(arr)}</div>`;
}

